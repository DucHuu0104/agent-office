let current: Locale = detectLocale();

export function getLocale(): Locale { return current; }
export function setLocale(locale: Locale): void {
  current = locale;
  try { localStorage.setItem('agent-office:locale', locale); } catch { /* The current tab still applies the selected locale. */ }
}

export function tr(source: string, args?: readonly unknown[]): string {
  const value = (current === 'vi' ? translations.vi[source] : translations.en[source]) ?? source;
  return args ? value.replace(/\{(\d+)\}/g, (part, index: string) => Number(index) < args.length ? String(args[Number(index)]) : part) : value;
}

function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem('agent-office:locale');
    if (saved === 'vi' || saved === 'en') return saved;
  } catch { /* private browsing */ }
  const languages = navigator.languages ?? [navigator.language];
  return languages.some((language) => language.toLowerCase().startsWith('en')) ? 'en' : 'vi';
}

